"""Signed operator authority, verified outside the coding namespace.

Ed25519 detached signatures cover canonical JSON. The public verification key is
an operator trust anchor, never a key supplied by an approval document. Signing
keys are neither loaded nor generated by the live runner.
"""
import hashlib
import json
import math
import os
from pathlib import Path
import re
import subprocess
import tempfile
import time

from contract import canonical, micro

FOLLOWUP_DESIGN = 'controlled-live-objective-only-followup-v1'


def validate_renewal(aggregate, previous, *, historical=False):
    """One successor for the expired root, scoped to B; never an extra $2 grant."""
    if (aggregate.get('renewal_version') != 1 or type(aggregate.get('renewal_version')) is not int
            or previous.get('renewal_version') is not None
            or aggregate.get('renews_nonce') != previous.get('nonce')
            or aggregate.get('renews_sha256') != hashlib.sha256(canonical(previous)).hexdigest()
            or aggregate.get('nonce') == previous.get('nonce')
            or aggregate.get('renewal_run_id') != 'merge-intervals:B'
            or aggregate.get('budget_semantics') != 'cumulative-existing-ledger'
            or aggregate.get('predecessor_expires_at') != previous.get('expires_at')):
        raise ValueError('invalid_aggregate_renewal_continuity')
    for key in ('schema', 'kind', 'contract_sha256', 'ledger_path', 'authorized_spend_usd',
                'accept_no_provider_hard_cap'):
        if aggregate.get(key) != previous.get(key):
            raise ValueError('aggregate_renewal_changes_original_authority')
    if (previous.get('kind') != 'aggregate-spending' or previous.get('authorized_spend_usd') != '2.00'
            or previous.get('accept_no_provider_hard_cap') is not True
            or not previous['issued_at'] < previous['expires_at'] <= aggregate['issued_at']
            or not (aggregate['expires_at'] <= time.time() if historical else aggregate['issued_at'] <= time.time() < aggregate['expires_at'])):
        raise ValueError('aggregate_renewal_overlap_or_expiry')


def renewal_predecessor(config, aggregate):
    path = config.get('previous_aggregate_authorization_file')
    if aggregate.get('renewal_version') is None:
        if path:
            raise ValueError('unexpected_aggregate_predecessor')
        return None
    if not path or config.get('run_id') != 'merge-intervals:B' or config.get('followup') is not True:
        raise ValueError('aggregate_renewal_requires_B_predecessor')
    previous = signed_document(path, config['operator_public_key'], expired_predecessor=True)
    validate_renewal(aggregate, previous)
    return previous


def verify_aggregate_receipts(db, aggregate, previous=None, *, claimed=False):
    root = previous if previous is not None else aggregate
    digest = lambda value: hashlib.sha256(canonical(value)).hexdigest()
    if db.execute("SELECT nonce,digest FROM live_authority WHERE kind='aggregate'").fetchall() != [(root['nonce'], digest(root))]:
        raise ValueError('followup_original_aggregate_required')
    receipts = db.execute("SELECT nonce,digest,run FROM live_authority WHERE kind='aggregate-renewal'").fetchall()
    expected = [(aggregate['nonce'], digest(aggregate), 'aggregate-renewal:'+root['nonce'])] if previous is not None else []
    if previous is not None:
        collision = db.execute('SELECT kind,digest,run FROM live_authority WHERE nonce=?', (aggregate['nonce'],)).fetchone()
        if collision and collision != ('aggregate-renewal', digest(aggregate), expected[0][2]):
            raise ValueError('aggregate_renewal_nonce_already_used')
    if receipts and receipts != expected:
        raise ValueError('aggregate_renewal_fork_or_replay')
    if claimed and receipts != expected:
        raise ValueError('unclaimed_aggregate_renewal')


def verify_followup_ledger(config, contract, run, aggregate, *, unused=False, experiment_data=None):
    """Existing accounting only. Never bootstrap, rotate or mutate a follow-up ledger."""
    import sqlite3
    from contextlib import closing
    path = private_file(config['ledger_path'])
    with closing(sqlite3.connect(path.resolve().as_uri()+'?mode=ro', uri=True)) as db:
        db.execute('PRAGMA query_only=ON')
        row = db.execute('SELECT body FROM experiment_contract WHERE id=1').fetchone()
        if not row:
            raise ValueError('existing_experiment_contract_required')
        stored = json.loads(row[0])
        if (canonical({k: stored.get(k) for k in contract.data}) != canonical(contract.data)
                or run['run_id'] not in stored.get('coding_run_ids', [])
                or (experiment_data is not None and canonical(stored) != canonical(experiment_data))):
            raise ValueError('followup_immutable_contract_mismatch')
        verify_aggregate_receipts(db, aggregate, renewal_predecessor(config, aggregate))
        if (db.execute("SELECT status FROM run_controls WHERE stage='coding' AND run='merge-intervals:A'").fetchone() != ('INCOMPLETE',)
                or db.execute("SELECT COUNT(*) FROM live_authority WHERE kind='run' AND run='merge-intervals:A'").fetchone()[0] != 1):
            raise ValueError('followup_consumed_incomplete_A_required')
        if unused:
            if min(run['expires_at'], aggregate['expires_at']) < time.time()+300:
                raise ValueError('followup_authority_expires_before_run_deadline')
            for table in ('run_controls', 'live_authority', 'reservations', 'run_policies'):
                if db.execute(f'SELECT 1 FROM {table} WHERE run=?', (run['run_id'],)).fetchone():
                    raise ValueError('followup_run_already_used')
            if db.execute('SELECT 1 FROM live_authority WHERE nonce=?', (run['nonce'],)).fetchone():
                raise ValueError('followup_nonce_already_used')
            if db.execute("SELECT 1 FROM run_controls WHERE status='ACTIVE'").fetchone():
                raise ValueError('followup_active_run_conflict')
        total = db.execute('SELECT COALESCE(SUM(upper_micro),0) FROM reservations').fetchone()[0]
        coding = db.execute("SELECT COALESCE(SUM(upper_micro),0) FROM reservations WHERE stage='coding'").fetchone()[0]
        if unused and (total+120000 > 2000000 or coding+120000 > micro(stored['coding_allocation_usd'])):
            raise ValueError('followup_insufficient_remaining_budget')
        return total


def unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError('ambiguous_authorization')
        result[key] = value
    return result


def private_file(path):
    path = Path(path)
    if path.is_symlink() or not path.is_file():
        raise ValueError('authorization_file_required')
    st = path.stat()
    if st.st_uid != os.getuid() or st.st_mode & 0o077:
        raise ValueError('authorization_permissions')
    return path


def signed_document(path, public_key, *, expired_predecessor=False):
    raw = private_file(path).read_bytes()
    if len(raw) > 32768:
        raise ValueError('authorization_size')
    envelope = json.loads(raw, object_pairs_hook=unique,
                          parse_constant=lambda _: (_ for _ in ()).throw(ValueError('nonfinite')))
    if set(envelope) != {'payload', 'signature'}:
        raise ValueError('authorization_envelope')
    payload = envelope['payload']
    if not isinstance(payload, dict) or not re.fullmatch('[0-9a-f]{128}', envelope['signature']):
        raise ValueError('authorization_signature')
    key = Path(public_key)
    if key.is_symlink() or not key.is_file() or key.stat().st_mode & 0o022:
        raise ValueError('untrusted_public_key')
    kind = subprocess.run(['openssl', 'pkey', '-pubin', '-in', str(key), '-text', '-noout'],
                          capture_output=True, timeout=5)
    if kind.returncode or not kind.stdout.startswith(b'ED25519 Public-Key:'):
        raise ValueError('ed25519_public_key_required')
    with tempfile.TemporaryDirectory(prefix='fusion-signature-') as tmp:
        message = Path(tmp)/'message'; signature = Path(tmp)/'signature'
        message.write_bytes(canonical(payload))
        signature.write_bytes(bytes.fromhex(envelope['signature']))
        result = subprocess.run(['openssl', 'pkeyutl', '-verify', '-pubin', '-inkey', str(key),
                                 '-rawin', '-in', str(message), '-sigfile', str(signature)],
                                capture_output=True, timeout=5)
    if result.returncode:
        raise ValueError('authorization_signature_invalid')
    now = time.time()
    if (payload.get('schema') != 'fusion-live-v1' or payload.get('test_double') is not False
            or type(payload.get('issued_at')) not in (int, float)
            or type(payload.get('expires_at')) not in (int, float)
            or not math.isfinite(payload['issued_at']) or not math.isfinite(payload['expires_at'])
            or not payload['issued_at'] < payload['expires_at']
            or not (payload['expires_at'] <= now if expired_predecessor else payload['issued_at'] <= now < payload['expires_at'])
            or not re.fullmatch('[a-zA-Z0-9_-]{16,128}', payload.get('nonce', ''))):
        raise ValueError('authorization_context_or_time')
    return payload


def verify_authority(config, contract):
    run = signed_document(config['authorization_file'], config['operator_public_key'])
    aggregate = signed_document(config['aggregate_authorization_file'], config['operator_public_key'])
    if aggregate.get('reliability_version') is not None:
        from reliability_authorization import chain
        chain(config, aggregate)
    else:
        renewal_predecessor(config, aggregate)
    if run['nonce'] == aggregate['nonce']:
        raise ValueError('authorization_nonce_collision')
    ledger = str(Path(config['ledger_path']).resolve())
    for document, kind in ((run, 'coding-run'), (aggregate, 'aggregate-spending')):
        if (document.get('kind') != kind or document.get('contract_sha256') != contract.sha256
                or document.get('ledger_path') != ledger):
            raise ValueError('authorization_binding')
    # Both signed authorities must explicitly accept the absence of an external
    # billing stop. Internal reservations bound dispatch, not provider billing.
    acknowledgments = [d.get('accept_no_provider_hard_cap') for d in (run, aggregate)]
    if run.get('provider_side_cap_confirmed') is False:
        if any(value is not True for value in acknowledgments):
            raise ValueError('missing_provider_cap_acknowledgment')
    elif (run.get('provider_side_cap_confirmed') is not True
          or any(value is not None and value is not False for value in acknowledgments)):
        raise ValueError('contradictory_provider_cap_authority')
    if (aggregate.get('authorized_spend_usd') != '2.00'
            or run.get('aggregate_nonce') != aggregate['nonce']
            or run.get('authorized_spend_usd') != '0.12'
            or run.get('run_id') != config['run_id'] or run.get('live_authorized') is not True
            or run.get('model') != contract.data['model']
            or run.get('approved_hosts') != ['api.openai.com']
            or run.get('model_availability_verified') is not True
            or not isinstance(run.get('model_availability_evidence'), str)
            or not run['model_availability_evidence'].strip()
            or run.get('pricing_verified') is not True
            or run.get('max_requests') != 4 or run.get('max_seconds') != 300):
        raise ValueError('authorization_limits_or_evidence')
    d = contract.data
    from decimal import Decimal
    if (Decimal(d['input_usd_per_million']) <= 0 or Decimal(d['output_usd_per_million']) <= 0
            or not 0 <= Decimal(d['cached_input_usd_per_million']) <= Decimal(d['input_usd_per_million'])):
        raise ValueError('uncertain_live_prices')
    if (micro(d['aggregate_cap_usd']) != 2000000 or micro(d['per_run_coding_cap_usd']) != 120000
            or d['coding_attempts_per_run'] != 4 or d['coding_seconds'] != 300
            or not 0 < d['request_seconds'] <= 60
            or not 0 < d['max_input_tokens'] <= 32000 or not 0 < d['max_output_tokens'] <= 4096):
        raise ValueError('unsafe_live_contract')
    errors = set(contract.arming_errors()) - {'NO_PAID_AUTHORIZATION', 'MODEL_AVAILABILITY_UNVERIFIED'}
    if errors:
        raise ValueError('contract_not_armable')
    if not Path(run['key_file']).is_absolute():
        raise ValueError('absolute_credential_path_required')
    private_file(run['key_file'])  # Metadata only; credentials are read only by the paid worker.
    if config.get('run_id') == 'merge-intervals:B':
        if (config.get('followup') is not True or run.get('followup_authorized') is not True
                or run.get('experiment_design') != FOLLOWUP_DESIGN
                or run.get('historical_phase2n_arm') is not False
                or run.get('predecessor_run_id') != 'merge-intervals:A'
                or run.get('task_id') != 'merge-intervals'):
            raise ValueError('objective_only_followup_authority_required')
        verify_followup_ledger(config, contract, run, aggregate)
    elif config.get('reliability'):
        from reliability_authorization import verify_ledger
        verify_ledger(config, contract, run, aggregate)
    elif config.get('followup') or config.get('run_id') != 'merge-intervals:A':
        raise ValueError('unsupported_live_run_design')
    return run, aggregate


def claim(ledger, run, aggregate, *, previous_aggregate=None, reliability_config=None):
    """One durable consumption, with no resume/retry/replacement-ledger fallback."""
    with ledger.connect() as db:
        db.execute('BEGIN IMMEDIATE')
        db.execute('CREATE TABLE IF NOT EXISTS live_authority (kind TEXT NOT NULL, nonce TEXT PRIMARY KEY, digest TEXT NOT NULL, run TEXT UNIQUE)')
        db.execute("CREATE TRIGGER IF NOT EXISTS live_authority_no_update BEFORE UPDATE ON live_authority BEGIN SELECT RAISE(ABORT,'immutable_live_authority'); END")
        db.execute("CREATE TRIGGER IF NOT EXISTS live_authority_no_delete BEFORE DELETE ON live_authority BEGIN SELECT RAISE(ABORT,'immutable_live_authority'); END")
        digest = lambda value: hashlib.sha256(canonical(value)).hexdigest()
        if aggregate.get('reliability_version') is not None:
            from reliability_authorization import receipts
            if reliability_config is None or run.get('run_id') != reliability_config.get('run_id') or run.get('aggregate_nonce') != aggregate['nonce']:
                raise ValueError('reliability_scope_required')
            previous = receipts(db, reliability_config, aggregate)
            db.execute('INSERT INTO live_authority VALUES (?,?,?,?)',
                       ('aggregate-reliability-continuation', aggregate['nonce'], digest(aggregate), 'aggregate-reliability-continuation:'+previous['nonce']))
        elif aggregate.get('renewal_version') is not None:
            if previous_aggregate is None or run.get('run_id') != 'merge-intervals:B' or run.get('aggregate_nonce') != aggregate['nonce']:
                raise ValueError('aggregate_renewal_predecessor_required')
            validate_renewal(aggregate, previous_aggregate)
            verify_aggregate_receipts(db, aggregate, previous_aggregate)
            db.execute('INSERT INTO live_authority VALUES (?,?,?,?)',
                       ('aggregate-renewal', aggregate['nonce'], digest(aggregate), 'aggregate-renewal:'+previous_aggregate['nonce']))
        else:
            if previous_aggregate is not None:
                raise ValueError('unexpected_aggregate_predecessor')
            previous = db.execute("SELECT nonce,digest FROM live_authority WHERE kind='aggregate'").fetchall()
            if previous and previous != [(aggregate['nonce'], digest(aggregate))]:
                raise ValueError('aggregate_authorization_changed')
            if not previous:
                db.execute('INSERT INTO live_authority VALUES (?,?,?,NULL)', ('aggregate', aggregate['nonce'], digest(aggregate)))
        db.execute('INSERT INTO live_authority VALUES (?,?,?,?)', ('run', run['nonce'], digest(run), run['run_id']))


def paid_gate(config, contract):
    run, aggregate = verify_authority(config, contract)
    # Open an existing DB read-only: transport must never bootstrap a ledger.
    import sqlite3
    from contextlib import closing
    with closing(sqlite3.connect(Path(config['ledger_path']).resolve().as_uri()+'?mode=ro', uri=True)) as db:
        if aggregate.get('reliability_version') is not None:
            from reliability_authorization import receipts
            receipts(db, config, aggregate, claimed=True)
        elif aggregate.get('renewal_version') is not None:
            verify_aggregate_receipts(db, aggregate, renewal_predecessor(config, aggregate), claimed=True)
        elif db.execute("SELECT digest FROM live_authority WHERE kind='aggregate' AND nonce=?",
                        (aggregate['nonce'],)).fetchone() != (hashlib.sha256(canonical(aggregate)).hexdigest(),):
            raise ValueError('unclaimed_aggregate_authorization')
        expected = hashlib.sha256(canonical(run)).hexdigest()
        if db.execute("SELECT digest FROM live_authority WHERE kind='run' AND nonce=? AND run=?",
                      (run['nonce'], run['run_id'])).fetchone() != (expected,):
            raise ValueError('unconsumed_authorization')
        control = db.execute("SELECT started,deadline,status FROM run_controls WHERE stage='coding' AND run=?", (run['run_id'],)).fetchone()
        if not control or control[2] != 'ACTIVE' or not control[0] <= time.time() < control[1]:
            raise ValueError('inactive_paid_run')
        total = db.execute('SELECT COALESCE(SUM(upper_micro),0) FROM reservations').fetchone()[0]
        used, count = db.execute("SELECT COALESCE(SUM(upper_micro),0),COUNT(*) FROM reservations WHERE stage='coding' AND run=?", (run['run_id'],)).fetchone()
        states = [row[0] for row in db.execute("SELECT (SELECT state FROM transitions WHERE reservation_id=r.id ORDER BY id DESC LIMIT 1) FROM reservations r WHERE stage='coding' AND run=? ORDER BY id", (run['run_id'],))]
        if not 0 < total <= 2000000 or not 0 < used <= 120000 or not 0 < count <= 4 or states != ['SETTLED']*(count-1)+['FORWARDED']:
            raise ValueError('unreserved_or_uncertain_paid_transport')
    return run
