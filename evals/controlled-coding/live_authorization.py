"""Signed operator authority, verified outside the coding namespace.

Ed25519 detached signatures cover canonical JSON. The public verification key is
an operator trust anchor, never a key supplied by an approval document. Signing
keys are neither loaded nor generated by the live runner.
"""
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import time

from contract import canonical, micro


def unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError('ambiguous_authorization')
        result[key] = value
    return result


def private_file(path):
    path = Path(path)
    if path.is_symlink() or not path.is_file():
        raise ValueError('authorization_file_required')
    st = path.stat()
    if st.st_uid != os.getuid() or st.st_mode & 0o077:
        raise ValueError('authorization_permissions')
    return path


def signed_document(path, public_key):
    raw = private_file(path).read_bytes()
    if len(raw) > 32768:
        raise ValueError('authorization_size')
    envelope = json.loads(raw, object_pairs_hook=unique,
                          parse_constant=lambda _: (_ for _ in ()).throw(ValueError('nonfinite')))
    if set(envelope) != {'payload', 'signature'}:
        raise ValueError('authorization_envelope')
    payload = envelope['payload']
    if not isinstance(payload, dict) or not re.fullmatch('[0-9a-f]{128}', envelope['signature']):
        raise ValueError('authorization_signature')
    key = Path(public_key)
    if key.is_symlink() or not key.is_file() or key.stat().st_mode & 0o022:
        raise ValueError('untrusted_public_key')
    kind = subprocess.run(['openssl', 'pkey', '-pubin', '-in', str(key), '-text', '-noout'],
                          capture_output=True, timeout=5)
    if kind.returncode or not kind.stdout.startswith(b'ED25519 Public-Key:'):
        raise ValueError('ed25519_public_key_required')
    with tempfile.TemporaryDirectory(prefix='fusion-signature-') as tmp:
        message = Path(tmp)/'message'; signature = Path(tmp)/'signature'
        message.write_bytes(canonical(payload))
        signature.write_bytes(bytes.fromhex(envelope['signature']))
        result = subprocess.run(['openssl', 'pkeyutl', '-verify', '-pubin', '-inkey', str(key),
                                 '-rawin', '-in', str(message), '-sigfile', str(signature)],
                                capture_output=True, timeout=5)
    if result.returncode:
        raise ValueError('authorization_signature_invalid')
    now = time.time()
    if (payload.get('schema') != 'fusion-live-v1' or payload.get('test_double') is not False
            or type(payload.get('issued_at')) not in (int, float)
            or type(payload.get('expires_at')) not in (int, float)
            or not payload['issued_at'] <= now < payload['expires_at']
            or not re.fullmatch('[a-zA-Z0-9_-]{16,128}', payload.get('nonce', ''))):
        raise ValueError('authorization_context_or_time')
    return payload


def verify_authority(config, contract):
    run = signed_document(config['authorization_file'], config['operator_public_key'])
    aggregate = signed_document(config['aggregate_authorization_file'], config['operator_public_key'])
    ledger = str(Path(config['ledger_path']).resolve())
    for document, kind in ((run, 'coding-run'), (aggregate, 'aggregate-spending')):
        if (document.get('kind') != kind or document.get('contract_sha256') != contract.sha256
                or document.get('ledger_path') != ledger):
            raise ValueError('authorization_binding')
    if (aggregate.get('authorized_spend_usd') != '2.00'
            or run.get('aggregate_nonce') != aggregate['nonce']
            or run.get('authorized_spend_usd') != '0.12'
            or run.get('run_id') != config['run_id'] or run.get('live_authorized') is not True
            or run.get('model') != contract.data['model']
            or run.get('approved_hosts') != ['api.openai.com']
            or run.get('provider_side_cap_confirmed') is not True
            or run.get('model_availability_verified') is not True
            or not isinstance(run.get('model_availability_evidence'), str)
            or not run['model_availability_evidence'].strip()
            or run.get('pricing_verified') is not True
            or run.get('max_requests') != 4 or run.get('max_seconds') != 300):
        raise ValueError('authorization_limits_or_evidence')
    d = contract.data
    from decimal import Decimal
    if (Decimal(d['input_usd_per_million']) <= 0 or Decimal(d['output_usd_per_million']) <= 0
            or not 0 <= Decimal(d['cached_input_usd_per_million']) <= Decimal(d['input_usd_per_million'])):
        raise ValueError('uncertain_live_prices')
    if (micro(d['aggregate_cap_usd']) != 2000000 or micro(d['per_run_coding_cap_usd']) != 120000
            or d['coding_attempts_per_run'] != 4 or d['coding_seconds'] != 300
            or not 0 < d['request_seconds'] <= 60
            or not 0 < d['max_input_tokens'] <= 32000 or not 0 < d['max_output_tokens'] <= 4096):
        raise ValueError('unsafe_live_contract')
    errors = set(contract.arming_errors()) - {'NO_PAID_AUTHORIZATION', 'MODEL_AVAILABILITY_UNVERIFIED'}
    if errors:
        raise ValueError('contract_not_armable')
    if not Path(run['key_file']).is_absolute():
        raise ValueError('absolute_credential_path_required')
    private_file(run['key_file'])  # Metadata only; credentials are read only by the paid worker.
    return run, aggregate


def claim(ledger, run, aggregate):
    """One durable consumption, with no resume/retry/replacement-ledger fallback."""
    with ledger.connect() as db:
        db.execute('BEGIN IMMEDIATE')
        db.execute('CREATE TABLE IF NOT EXISTS live_authority (kind TEXT NOT NULL, nonce TEXT PRIMARY KEY, digest TEXT NOT NULL, run TEXT UNIQUE)')
        db.execute("CREATE TRIGGER IF NOT EXISTS live_authority_no_update BEFORE UPDATE ON live_authority BEGIN SELECT RAISE(ABORT,'immutable_live_authority'); END")
        db.execute("CREATE TRIGGER IF NOT EXISTS live_authority_no_delete BEFORE DELETE ON live_authority BEGIN SELECT RAISE(ABORT,'immutable_live_authority'); END")
        digest = lambda value: hashlib.sha256(canonical(value)).hexdigest()
        previous = db.execute("SELECT nonce,digest FROM live_authority WHERE kind='aggregate'").fetchall()
        if previous and previous != [(aggregate['nonce'], digest(aggregate))]:
            raise ValueError('aggregate_authorization_changed')
        if not previous:
            db.execute('INSERT INTO live_authority VALUES (?,?,?,NULL)', ('aggregate', aggregate['nonce'], digest(aggregate)))
        db.execute('INSERT INTO live_authority VALUES (?,?,?,?)', ('run', run['nonce'], digest(run), run['run_id']))


def paid_gate(config, contract):
    run, aggregate = verify_authority(config, contract)
    # Open an existing DB read-only: transport must never bootstrap a ledger.
    import sqlite3
    from contextlib import closing
    with closing(sqlite3.connect(Path(config['ledger_path']).resolve().as_uri()+'?mode=ro', uri=True)) as db:
        if db.execute("SELECT digest FROM live_authority WHERE kind='aggregate' AND nonce=?",
                      (aggregate['nonce'],)).fetchone() != (hashlib.sha256(canonical(aggregate)).hexdigest(),):
            raise ValueError('unclaimed_aggregate_authorization')
        expected = hashlib.sha256(canonical(run)).hexdigest()
        if db.execute("SELECT digest FROM live_authority WHERE kind='run' AND nonce=? AND run=?",
                      (run['nonce'], run['run_id'])).fetchone() != (expected,):
            raise ValueError('unconsumed_authorization')
        control = db.execute("SELECT started,deadline,status FROM run_controls WHERE stage='coding' AND run=?", (run['run_id'],)).fetchone()
        if not control or control[2] != 'ACTIVE' or not control[0] <= time.time() < control[1]:
            raise ValueError('inactive_paid_run')
        total = db.execute('SELECT COALESCE(SUM(upper_micro),0) FROM reservations').fetchone()[0]
        used, count = db.execute("SELECT COALESCE(SUM(upper_micro),0),COUNT(*) FROM reservations WHERE stage='coding' AND run=?", (run['run_id'],)).fetchone()
        states = [row[0] for row in db.execute("SELECT (SELECT state FROM transitions WHERE reservation_id=r.id ORDER BY id DESC LIMIT 1) FROM reservations r WHERE stage='coding' AND run=? ORDER BY id", (run['run_id'],))]
        if not 0 < total <= 2000000 or not 0 < used <= 120000 or not 0 < count <= 4 or states != ['SETTLED']*(count-1)+['FORWARDED']:
            raise ValueError('unreserved_or_uncertain_paid_transport')
    return run
