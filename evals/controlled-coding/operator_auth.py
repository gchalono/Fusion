class ApprovalVerifier:
 def __init__(self,trust,envelope,*,test_only=False):
  self.trust=Path(trust);self.envelope=envelope;self.test_only=test_only
  if set(envelope)!={'payload','signature','key_id'} or set(envelope['payload'])!={'spec','transport'}:raise ValueError('approval_schema')
  self.payload=envelope['payload'];self.spec=self.payload['spec'];domain=TEST_DOMAIN if test_only else LIVE_DOMAIN
  if self.spec.get('domain')!=domain:raise ValueError('approval_domain_unavailable')
  if not test_only:
   if self.trust!=LIVE_TRUST:raise ValueError('operator_trust_path_fixed')
   for p in (self.trust,self.trust.parent):
    if p.is_symlink() or p.stat().st_uid!=0 or p.stat().st_mode&0o022:raise ValueError('operator_trust_requires_root_ownership_and_no_dev_write')
  elif not (self.trust.parent/'.test-domain').is_file():raise ValueError('test_trust_marker_required')
  trust_data=strict(self.trust.read_bytes())
  if trust_data.get('domain')!=domain or trust_data.get('algorithm')!='Ed25519':raise ValueError('trust_domain_or_algorithm')
  self.public=self.trust.parent/'operator.pub'
  if self.public.is_symlink() or (not test_only and (self.public.stat().st_uid!=0 or self.public.stat().st_mode&0o022)):raise ValueError('untrusted_public_key_path')
  self.key_id=public_fingerprint(self.public)
  if trust_data.get('key_id')!=self.key_id or envelope['key_id']!=self.key_id:raise ValueError('unknown_or_substituted_signing_key')
  if not self(self.spec,envelope['signature']):raise ValueError('invalid_operator_signature')
